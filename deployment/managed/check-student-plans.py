"""Verify public UI assets and ownership of teacher-generated student paths."""
import re
import requests


def main():
    base = 'https://openclass-jdi6nfaqza-uc.a.run.app'
    page = requests.get(base, timeout=30)
    page.raise_for_status()
    asset = re.search(r'src="([^"]+\.js)"', page.text).group(1)
    bundle = requests.get(base+asset, timeout=30)
    bundle.raise_for_status()
    assert 'Your AI learning plans' in bundle.text
    assert 'Generated by your teacher' in bundle.text
    assert 'Agents & sessions' not in bundle.text and 'Services & setup' not in bundle.text
    print('PASS: deployed UI contains student plan view and excludes removed navigation labels')
    with requests.Session() as session:
        response = session.post(base+'/api/auth/login', json={'email': 'student@openclass.demo', 'password': 'OpenClass123!'}, timeout=30)
        response.raise_for_status()
        try:
            response = session.get(base+'/api/courses/machine-learning/self-study', timeout=30)
            response.raise_for_status()
            items = response.json()
            assert all(row['student_id'] == 'student-1' for row in items)
            paths = [row for row in items if row['type'] == 'path']
            generated = [row for row in paths if not row.get('synthetic') and row['status'] == 'completed' and row.get('requested_by') != row['student_id']]
            print('Student paths:', len(paths), '; completed teacher-generated paths:', len(generated))
            assert generated, 'No completed teacher-generated plan exists for this account'
        finally:
            session.post(base+'/api/auth/logout', timeout=30).raise_for_status()


if __name__ == '__main__':
    main()
